/**
 * Static-text dictionary for the PDF report (`report.service.ts`) — the
 * report's own structural strings (headings, table headers, fixed
 * phrases) plus enum-value labels, translated to match whatever language
 * the platform's UI is currently in (see `docs/report-redesign-proposal.md`
 * §2). This is intentionally a separate, minimal dictionary from
 * `apps/web/src/i18n/locales/*` — those are `react-i18next` namespaces tied
 * to a browser `i18next` instance; this runs server-side in a Workers
 * request with no such runtime, so it's a plain lookup table instead.
 * Terminology is kept consistent with the frontend's existing `audit.json`/
 * `envelope.json`/`measures.json` namespaces where the same concept already
 * has an established translation there (e.g. "Chora-tadbir"/"Мероприятие"
 * for "Measure", "kVt·soat"/"кВт·ч" for "kWh" — the platform already
 * localizes physical units, not just labels, so the report does too).
 *
 * Measure names, ancillary-cost descriptions, and construction-type/auditor
 * notes are freeform user-entered text from the database, not translated —
 * only this file's own static structural text and the fixed enum values
 * below are.
 */

export type ReportLang = "en" | "ru" | "uz";

export function isReportLang(value: string | null | undefined): value is ReportLang {
  return value === "en" || value === "ru" || value === "uz";
}

export function localeTag(lang: ReportLang): string {
  if (lang === "ru") return "ru-RU";
  if (lang === "uz") return "uz-UZ";
  return "en-US";
}

